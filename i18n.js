  try {
    const param = new URLSearchParams(location.search).get('lang');
    const saved = localStorage.getItem('sp-lang');
    if (param === 'el' || param === 'en') start = param;
    else if (saved === 'el' || saved === 'en') start = saved;
    else if ((navigator.language || '').toLowerCase().startsWith('el')) start = 'el';
  } catch (e) {}
  apply(start);

  const btn = document.querySelector('.lang-toggle');
  if (btn) btn.addEventListener('click', () => apply(lang === 'en' ? 'el' : 'en'));
